-- Telium Phase 1 schema.
--
-- Three roles share one database file in the single-binary deployment; tables are
-- grouped by the role that owns them. Nothing here assumes a user id is immutable
-- forever (plan Section 3): user ids are plain TEXT columns with no foreign keys
-- across the identity/guild boundary, so a Section 10 tombstone remap is an UPDATE.

-- ---------------------------------------------------------------- server-wide

CREATE TABLE server_keys (
    key_id      TEXT PRIMARY KEY,
    secret_b64  TEXT NOT NULL,
    public_b64  TEXT NOT NULL,
    valid_from  INTEGER NOT NULL,
    valid_until INTEGER NOT NULL
);

-- ------------------------------------------------------------- identity role

CREATE TABLE accounts (
    user_id       TEXT PRIMARY KEY,          -- @alice:home.example
    localpart     TEXT NOT NULL,
    domain        TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    created_at    INTEGER NOT NULL,
    deactivated   INTEGER NOT NULL DEFAULT 0,
    admin         INTEGER NOT NULL DEFAULT 0,
    UNIQUE (localpart, domain)
);

CREATE TABLE devices (
    device_id  TEXT PRIMARY KEY,
    user_id    TEXT NOT NULL,
    name       TEXT NOT NULL,
    pubkey_b64 TEXT NOT NULL,               -- Ed25519, generated by the device at login
    created_at INTEGER NOT NULL,
    last_seen  INTEGER NOT NULL,
    active     INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX devices_user ON devices (user_id);

-- Client <-> home server sessions (not federation-visible).
CREATE TABLE home_sessions (
    token_hash TEXT PRIMARY KEY,
    user_id    TEXT NOT NULL,
    device_id  TEXT NOT NULL,
    created_at INTEGER NOT NULL,
    expires_at INTEGER NOT NULL
);
CREATE INDEX home_sessions_user ON home_sessions (user_id);

CREATE TABLE profiles (
    user_id         TEXT PRIMARY KEY,
    display_name    TEXT NOT NULL,
    avatar_ref      TEXT,
    banner_ref      TEXT,
    accent_color    INTEGER,
    bio             TEXT,
    pronouns        TEXT,
    profile_version INTEGER NOT NULL DEFAULT 1,
    updated_at      INTEGER NOT NULL
);

-- Small per-account key/value store: GIF favourites, frequent emoji, drafts,
-- notification prefs. Bounded (Section 3) and part of the migration bundle later.
CREATE TABLE sync_store (
    user_id    TEXT NOT NULL,
    key        TEXT NOT NULL,
    value      TEXT NOT NULL,
    updated_at INTEGER NOT NULL,
    PRIMARY KEY (user_id, key)
);

-- --------------------------------------------------------------- media role

CREATE TABLE media (
    hash          TEXT PRIMARY KEY,          -- BLAKE3 hex; content address
    owner_user_id TEXT NOT NULL,
    filename      TEXT NOT NULL,
    mime          TEXT NOT NULL,
    size          INTEGER NOT NULL,
    width         INTEGER,
    height        INTEGER,
    thumbhash     TEXT,
    capability    TEXT NOT NULL,             -- unguessable per-upload token
    purpose       TEXT NOT NULL,             -- attachment | profile | expression
    created_at    INTEGER NOT NULL,
    refcount      INTEGER NOT NULL DEFAULT 1
);
CREATE INDEX media_owner ON media (owner_user_id);

-- ---------------------------------------------------------------- guild role

CREATE TABLE guilds (
    id            TEXT PRIMARY KEY,          -- immutable ULID; the alias is vanity
    alias         TEXT UNIQUE,               -- #gaming  (localpart only; domain is ours)
    name          TEXT NOT NULL,
    icon_ref      TEXT,
    owner_user_id TEXT NOT NULL,
    settings      TEXT NOT NULL DEFAULT '{}',
    created_at    INTEGER NOT NULL
);

CREATE TABLE channels (
    id         TEXT PRIMARY KEY,
    guild_id   TEXT NOT NULL,
    type       TEXT NOT NULL,                -- text | voice | forum | announcement | category
    name       TEXT NOT NULL,
    topic      TEXT,
    position   INTEGER NOT NULL DEFAULT 0,
    parent_id  TEXT,
    slowmode   INTEGER NOT NULL DEFAULT 0,
    created_at INTEGER NOT NULL
);
CREATE INDEX channels_guild ON channels (guild_id);

CREATE TABLE channel_overwrites (
    channel_id  TEXT NOT NULL,
    target_type TEXT NOT NULL,               -- role | member
    target_id   TEXT NOT NULL,
    allow       INTEGER NOT NULL DEFAULT 0,
    deny        INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (channel_id, target_type, target_id)
);

CREATE TABLE roles (
    id          TEXT PRIMARY KEY,            -- @everyone has id == guild_id
    guild_id    TEXT NOT NULL,
    name        TEXT NOT NULL,
    color       INTEGER NOT NULL DEFAULT 0,
    position    INTEGER NOT NULL DEFAULT 0,
    permissions INTEGER NOT NULL DEFAULT 0,
    hoist       INTEGER NOT NULL DEFAULT 0,
    mentionable INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX roles_guild ON roles (guild_id);

-- display_name / avatar_ref / profile_version are the cached "display essentials"
-- of Section 3: pushed at join, refreshed lazily, and the reason member-list
-- scrolling never touches a foreign homeserver.
CREATE TABLE members (
    guild_id        TEXT NOT NULL,
    user_id         TEXT NOT NULL,
    nickname        TEXT,
    joined_at       INTEGER NOT NULL,
    timeout_until   INTEGER,
    banned          INTEGER NOT NULL DEFAULT 0,
    ban_reason      TEXT,
    display_name    TEXT NOT NULL DEFAULT '',
    avatar_ref      TEXT,
    profile_version INTEGER NOT NULL DEFAULT 0,
    PRIMARY KEY (guild_id, user_id)
);

CREATE TABLE member_roles (
    guild_id TEXT NOT NULL,
    user_id  TEXT NOT NULL,
    role_id  TEXT NOT NULL,
    PRIMARY KEY (guild_id, user_id, role_id)
);

CREATE TABLE messages (
    id               TEXT PRIMARY KEY,       -- ULID, time-sortable
    channel_id       TEXT NOT NULL,
    guild_id         TEXT NOT NULL,
    author_id        TEXT NOT NULL,
    content          TEXT NOT NULL,
    attachments      TEXT NOT NULL DEFAULT '[]',
    reply_to         TEXT,
    thread_id        TEXT,
    author_signature TEXT,                   -- opt-in device-key signature
    created_at       INTEGER NOT NULL,
    edited_at        INTEGER,
    deleted          INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX messages_channel ON messages (channel_id, id DESC);

CREATE TABLE emojis (
    id         TEXT PRIMARY KEY,
    guild_id   TEXT NOT NULL,
    name       TEXT NOT NULL,
    media_hash TEXT NOT NULL,
    animated   INTEGER NOT NULL DEFAULT 0,
    uploader   TEXT NOT NULL,
    created_at INTEGER NOT NULL,
    UNIQUE (guild_id, name)
);

CREATE TABLE stickers (
    id         TEXT PRIMARY KEY,
    guild_id   TEXT NOT NULL,
    name       TEXT NOT NULL,
    media_hash TEXT NOT NULL,
    format     TEXT NOT NULL,
    uploader   TEXT NOT NULL,
    created_at INTEGER NOT NULL,
    UNIQUE (guild_id, name)
);

CREATE TABLE invites (
    code       TEXT PRIMARY KEY,
    guild_id   TEXT NOT NULL,
    channel_id TEXT,
    creator    TEXT NOT NULL,
    uses       INTEGER NOT NULL DEFAULT 0,
    max_uses   INTEGER,
    expires_at INTEGER,
    created_at INTEGER NOT NULL
);
CREATE INDEX invites_guild ON invites (guild_id);

-- Local session tokens minted by the guild role after verifying an identity
-- assertion. The home server is off the hot path once this exists (Section 3).
CREATE TABLE guild_sessions (
    token_hash    TEXT PRIMARY KEY,
    user_id       TEXT NOT NULL,
    device_id     TEXT NOT NULL,
    home_domain   TEXT NOT NULL,
    -- Display essentials carried in on the assertion, so a join never has to ask
    -- the member's homeserver anything (Section 3).
    display_name  TEXT NOT NULL DEFAULT '',
    avatar_ref    TEXT,
    created_at    INTEGER NOT NULL,
    expires_at    INTEGER NOT NULL,
    revalidate_at INTEGER NOT NULL
);
CREATE INDEX guild_sessions_user ON guild_sessions (user_id);

CREATE TABLE audit_log (
    id         TEXT PRIMARY KEY,
    guild_id   TEXT NOT NULL,
    actor      TEXT NOT NULL,
    action     TEXT NOT NULL,
    target     TEXT,
    data       TEXT NOT NULL DEFAULT '{}',
    created_at INTEGER NOT NULL
);
CREATE INDEX audit_guild ON audit_log (guild_id, id DESC);
